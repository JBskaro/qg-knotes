_CODE_NAMES = {disk: code for code, disk in LEGACY_NAMES.items()}


def to_disk(fields: dict) -> dict:
    """Fields named as in code -> as in the file; one level, nested data keeps its keys."""
    return {LEGACY_NAMES.get(key, key): value for key, value in fields.items()}


def from_disk(data: dict) -> dict:
    """Fields named as in the file -> as in code."""
    return {_CODE_NAMES.get(key, key): value for key, value in data.items()}
